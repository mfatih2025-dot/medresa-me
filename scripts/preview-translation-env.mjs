import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

// Capture no values, lengths, hashes or environment dump. Never print the key.
export function buildTranslationPresence(environment) {
  const value = environment.OPENAI_API_KEY;
  const sha = environment.VERCEL_GIT_COMMIT_SHA;
  return {
  captured: true,
  keyDefined: typeof value === "string",
  keyNonEmpty: typeof value === "string" && value.length > 0,
  keyHasNonWhitespace: typeof value === "string" && value.trim().length > 0,
  previewEnvironment: environment.VERCEL_ENV === "preview",
  adminBranch: environment.VERCEL_GIT_COMMIT_REF === "codex/admin-panel",
  commitSha: sha && /^[a-f0-9]{40}$/.test(sha) && sha !== value ? sha : null,
  };
}
// The generated file contains public commit metadata and booleans, never secrets.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(fileURLToPath(new URL("../src/server/admin/translationBuildPresence.ts", import.meta.url)),
    `/** Generated by the prebuild hook; presence evidence only. */\nexport const translationBuildPresence = ${JSON.stringify(buildTranslationPresence(process.env), null, 2)};\n`);
}
